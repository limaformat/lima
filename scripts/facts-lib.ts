export type FactValue = string | number | FactTree
export interface FactTree { [key: string]: FactValue }

export interface MarkerDifference {
	key: string
	actual: string
	expected: string
}

const markerPattern = /<!-- facts:([a-z0-9_.-]+) -->([\s\S]*?)<!-- \/facts -->/g

export const flattenFacts = (facts: FactTree, prefix = ''): Map<string, string | number> => {
	const flat = new Map<string, string | number>()
	for (const [key, value] of Object.entries(facts)) {
		const path = prefix ? `${prefix}.${key}` : key
		if (typeof value === 'object') {
			for (const [nestedKey, nestedValue] of flattenFacts(value, path)) flat.set(nestedKey, nestedValue)
		} else flat.set(path, value)
	}
	return flat
}

export const renderMarkerValue = (value: string | number): string =>
	typeof value === 'number' ? value.toLocaleString('en-US', { maximumFractionDigits: 20 }) : value

export const replaceFactMarkers = (
	source: string,
	facts: FactTree,
): { text: string; differences: MarkerDifference[]; keys: string[] } => {
	const flat = flattenFacts(facts)
	const differences: MarkerDifference[] = []
	const keys: string[] = []
	const text = source.replace(markerPattern, (_whole, key: string, actual: string) => {
		const value = flat.get(key)
		if (value === undefined) throw new Error(`unknown fact marker: ${key}`)
		const expected = renderMarkerValue(value)
		keys.push(key)
		if (actual !== expected) differences.push({ key, actual, expected })
		return `<!-- facts:${key} -->${expected}<!-- /facts -->`
	})
	return { text, differences, keys }
}

const quote = (value: string): string => JSON.stringify(value)

const formatNode = (node: FactTree, indent: number): string[] => {
	const lines: string[] = []
	for (const [key, value] of Object.entries(node)) {
		const prefix = `${'  '.repeat(indent)}${key}:`
		if (typeof value === 'object') lines.push(prefix, ...formatNode(value, indent + 1))
		else lines.push(`${prefix} ${typeof value === 'string' ? quote(value) : String(value)}`)
	}
	return lines
}

export const formatFacts = (facts: FactTree): string =>
	[
		'# Generated by scripts/facts.ts. Do not edit.',
		'# Regenerate with: bun scripts/facts.ts',
		'',
		...formatNode(facts, 0),
		'',
	].join('\n')

export interface FixedPointResult<T> {
	value: T
	rounds: number
}

/** Re-measure after every write because a generated value may affect its own measurement. */
export const reachFixedPoint = async <T>(
	measure: () => Promise<T>,
	apply: (value: T) => Promise<boolean>,
	maxRounds = 5,
): Promise<FixedPointResult<T>> => {
	for (let round = 1; round <= maxRounds; round++) {
		const value = await measure()
		if (!(await apply(value))) return { value, rounds: round }
	}
	throw new Error(`facts did not reach a fixed point after ${maxRounds} rounds`)
}
