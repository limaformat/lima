import { describe, expect, test } from 'bun:test'
import { formatFacts, reachFixedPoint, replaceFactMarkers } from '../../scripts/facts-lib'

describe('fact markers', () => {
	test('replaces values and reports differences', () => {
		const result = replaceFactMarkers('Cases: <!-- facts:corpus.cases -->2<!-- /facts -->.', { corpus: { cases: 1234 } })
		expect(result.text).toBe('Cases: <!-- facts:corpus.cases -->1,234<!-- /facts -->.')
		expect(result.differences).toEqual([{ key: 'corpus.cases', actual: '2', expected: '1,234' }])
	})

	test('rejects an unknown key', () => {
		expect(() => replaceFactMarkers('<!-- facts:nope -->1<!-- /facts -->', {})).toThrow('unknown fact marker: nope')
	})
})

test('facts formatting is deterministic Lima', () => {
	expect(formatFacts({ packages: { version: '1.2.3' }, corpus: { cases: 42 } })).toBe(
		'# Generated by scripts/facts.ts. Do not edit.\n' +
		'# Regenerate with: bun scripts/facts.ts\n\n' +
		'packages:\n  version: "1.2.3"\ncorpus:\n  cases: 42\n',
	)
})

test('fixed-point loop remeasures until a write changes nothing', async () => {
	let state = 1
	const result = await reachFixedPoint(
		async () => state,
		async (measured) => {
			if (measured < 3) { state++; return true }
			return false
		},
	)
	expect(result).toEqual({ value: 3, rounds: 3 })
})

test('fixed-point loop is bounded', async () => {
	await expect(reachFixedPoint(async () => 1, async () => true, 2)).rejects.toThrow('after 2 rounds')
})
